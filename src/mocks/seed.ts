export async function seedDatabase() {
  await templates.deleteMany(() => true);

  let nextId = 1;
  let groupCount = 0;
  let childCount = 0;

  for (const group of GROUPS) {
    // idTemplate и idGroup одинаковы у группы — это признак корневой записи
    const groupId = nextId++;

    await templates.create({
      idTemplate: groupId,
      nameTemplate: group.name,
      idGroup: groupId,
      nameGroup: group.name,
      status: 1, // у групп — «создан», чтобы не подсвечивать цветом
      dateCreate: randomDate(),
    });
    groupCount += 1;

    for (const childName of group.children) {
      const childId = nextId++;
      await templates.create({
        idTemplate: childId,
        nameTemplate: childName,
        idGroup: groupId,
        nameGroup: group.name,
        status: randomStatus(),
        dateCreate: randomDate(),
      });
      childCount += 1;
    }
  }

  console.log(`[seed] created ${groupCount} groups and ${childCount} plants`);
}