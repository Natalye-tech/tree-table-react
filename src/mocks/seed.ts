/** Дата в формате ДД.ММ.ГГГГ */
function formatDate(d: Date): string {
  const day = String(d.getDate()).padStart(2, '0');
  const month = String(d.getMonth() + 1).padStart(2, '0');
  const year = d.getFullYear();
  return `${day}.${month}.${year}`;
}

/** Случайная дата в пределах ±1 год от текущей */
function randomDate(): string {
  const now = new Date();
  const oneYearAgo = new Date(
    now.getFullYear() - 1,
    now.getMonth(),
    now.getDate(),
  );
  const oneYearAhead = new Date(
    now.getFullYear() + 1,
    now.getMonth(),
    now.getDate(),
  );
  const ms =
    oneYearAgo.getTime() +
    Math.random() * (oneYearAhead.getTime() - oneYearAgo.getTime());
  return formatDate(new Date(ms));
}

/**
 * Случайный статус:
 * 1 — создан
 * 2 — выполнен
 * 3 — ошибка
 * 4 — выполняется
 *
 * Распределение: 30% создан, 35% выполнен, 15% ошибка, 20% выполняется.
 */
function randomStatus(): number {
  const r = Math.random();
  if (r < 0.3) return 1;
  if (r < 0.65) return 2;
  if (r < 0.8) return 3;
  return 4;
}

